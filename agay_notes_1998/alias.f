      PROGRAM ALIAS
C     ------------------------------------------------------------------
      INTEGER I, J(5)
      EXTERNAL SUB
C     ------------------------------------------------------------------
      DO 1 I=1,5
        J(I) = 2
 1    CONTINUE
C     ------------------------------------------------------------------
      WRITE(*,*) 'BEFORE: ', J
      CALL SUB(J, J(1))
      WRITE(*,*) 'AFTER:  ', J
C     ------------------------------------------------------------------
      END

      SUBROUTINE SUB(K, L)
C     ------------------------------------------------------------------
      INTEGER I, K(5), L
C     ------------------------------------------------------------------
      DO 2 I=1,5
        K(I) = L * K(I)
 2    CONTINUE
C     ------------------------------------------------------------------
      RETURN
      END
