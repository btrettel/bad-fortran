      PROGRAM ALIAS
C     ------------------------------------------------------------------
      INTEGER
     *          I, A(5)
C     ------------------------------------------------------------------
      DO I=1,5
        A(I) = 2
      ENDDO
C     ------------------------------------------------------------------
      WRITE(*,*) 'Before: ', A
      CALL SUB(A, A(1))
      WRITE(*,*) 'After:  ', A
C     ------------------------------------------------------------------
      END


      SUBROUTINE SUB(X, Y)
C     ------------------------------------------------------------------
      INTEGER
     *          I, X(5), Y
C     ------------------------------------------------------------------
      DO I=1,5
        X(I) = Y * X(I)
      ENDDO
C     ------------------------------------------------------------------
      RETURN
      END
