      PROGRAM ALIAS
C     ------------------------------------------------------------------
      INTEGER
     *          I, A(5)
C     ------------------------------------------------------------------
      DO 1 I=1,5
        A(I) = 2
 1    CONTINUE
C     ------------------------------------------------------------------
      WRITE(*,*) 'BEFORE: ', A
      CALL SUB(A, A(1))
      WRITE(*,*) 'AFTER:  ', A
C     ------------------------------------------------------------------
      END


      SUBROUTINE SUB(X, Y)
C     ------------------------------------------------------------------
      INTEGER
     *          I, X(5), Y
C     ------------------------------------------------------------------
      DO 2 I=1,5
        X(I) = Y * X(I)
 2    CONTINUE
C     ------------------------------------------------------------------
      RETURN
      END
